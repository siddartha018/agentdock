"""Agent manifests: ``agents/<name>/agent.toml`` is the only config a team writes."""

from __future__ import annotations

import importlib.util
import json
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from types import ModuleType
from typing import Any

from agentdock.identity import ROOT

AGENTS_DIR = ROOT / "agents"
NAME_RE = re.compile(r"^[a-z][a-z0-9_]{2,40}$")
ROLES = {"employee", "manager", "hr"}
KINDS = {"react", "workflow"}


class ManifestError(ValueError):
    pass


@dataclass
class Gate:
    min_pass_rate: float = 0.9
    min_cases: int = 5


@dataclass
class Manifest:
    name: str
    description: str
    owner_team: str
    kind: str
    allowed_roles: list[str]
    path: Path
    gate: Gate = field(default_factory=Gate)
    stream: bool = False  # opt in to redacted token streaming

    @property
    def graph_file(self) -> Path:
        return self.path / "graph.py"

    @property
    def evals_file(self) -> Path:
        return self.path / "evals.jsonl"


def load_manifest(agent_dir: Path) -> Manifest:
    file = agent_dir / "agent.toml"
    if not file.exists():
        raise ManifestError(f"{agent_dir.name}: missing agent.toml")
    raw = tomllib.loads(file.read_text())
    problems = []
    name = raw.get("name", "")
    if name != agent_dir.name:
        problems.append(f"name {name!r} must match folder {agent_dir.name!r}")
    if not NAME_RE.match(name or ""):
        problems.append("name must be snake_case, 3-41 chars")
    if len(raw.get("description", "")) < 20:
        problems.append("description must be at least 20 chars (it becomes the MCP tool and A2A card text)")
    if "'" in raw.get("description", ""):
        # `langgraph build` puts descriptions in a single-quoted Dockerfile ENV line.
        problems.append("description must not contain an apostrophe (breaks `langgraph build`)")
    if not raw.get("owner_team"):
        problems.append("owner_team is required")
    if raw.get("kind") not in KINDS:
        problems.append(f"kind must be one of {sorted(KINDS)}")
    roles = raw.get("allowed_roles") or []
    if not roles or not set(roles) <= ROLES:
        problems.append(f"allowed_roles must be a non-empty subset of {sorted(ROLES)}")
    gate = Gate(**raw.get("gate", {}))
    if not isinstance(raw.get("stream", False), bool):
        problems.append("stream must be true or false")
    if not 0 < gate.min_pass_rate <= 1:
        problems.append("gate.min_pass_rate must be in (0, 1]")
    if problems:
        raise ManifestError(f"{agent_dir.name}: " + "; ".join(problems))
    return Manifest(
        name=name,
        description=raw["description"].strip(),
        owner_team=raw["owner_team"],
        kind=raw["kind"],
        allowed_roles=list(roles),
        path=agent_dir,
        gate=gate,
        stream=raw.get("stream", False),
    )


def discover(agents_dir: Path = AGENTS_DIR) -> list[Manifest]:
    return [
        load_manifest(d)
        for d in sorted(agents_dir.iterdir())
        if d.is_dir() and not d.name.startswith(("_", "."))
    ]


def import_agent_module(m: Manifest) -> ModuleType:
    modname = f"agentdock_agents.{m.name}"
    if modname in sys.modules:
        return sys.modules[modname]
    spec = importlib.util.spec_from_file_location(modname, m.graph_file)
    if spec is None or spec.loader is None:
        raise ManifestError(f"{m.name}: cannot import graph.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[modname] = module
    spec.loader.exec_module(module)
    if not callable(getattr(module, "build", None)):
        raise ManifestError(f"{m.name}: graph.py must define build() returning a graph")
    return module


def langgraph_config(manifests: list[Manifest], retention_minutes: int) -> dict[str, Any]:
    """The server config. Generated; never edited by hand."""
    return {
        "$comment": "Generated by `dock sync`. Edit agents/*/agent.toml instead.",
        "dependencies": ["."],
        "python_version": "3.13",
        "graphs": {
            m.name: {"path": "./src/agentdock/entry.py:" + m.name, "description": m.description}
            for m in manifests
        },
        "auth": {"path": "./src/agentdock/auth.py:auth"},
        "http": {"app": "./src/agentdock/http_app.py:app"},
        "env": ".env",
        "checkpointer": {
            "ttl": {
                "strategy": "delete",
                "default_ttl": retention_minutes,
                "sweep_interval_minutes": 10,
            }
        },
        "store": {"ttl": {"default_ttl": retention_minutes, "sweep_interval_minutes": 10}},
    }


def write_langgraph_config(manifests: list[Manifest], retention_minutes: int, path: Path | None = None) -> Path:
    path = path or ROOT / "langgraph.json"
    path.write_text(json.dumps(langgraph_config(manifests, retention_minutes), indent=2) + "\n")
    return path
